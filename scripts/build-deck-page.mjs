// Images uploaded to the deck, and the site's copy of each.
const BLOBS = {
  "/_blob/3ad878e9810c850f817fe9d57873338d": "../images/logo-light-120.png",
  "/_blob/62344af3a3677c77d6037c8594854f83": "../images/logo-dark-120.png",
};

const index = JSON.parse(readFileSync(join(deckDir, "deck.json"), "utf8"));

const slides = index.order.map((id, i) => {
  let html = readFileSync(join(deckDir, "slides", `${id}.html`), "utf8");
  html = html.replace(/<aside>[\s\S]*?<\/aside>/g, "");
  html = html.replace(/<x-icon name="(\w+)" style="([^"]*)"><\/x-icon>/g, (_, name, style) => {
    if (!ICONS[name]) throw new Error(`slide ${id}: no SVG for icon "${name}" — add it to ICONS`);
    return '<svg aria-hidden="true" viewBox="0 0 24 24" fill="none" stroke="currentColor" ' +
      `stroke-width="2" stroke-linecap="round" stroke-linejoin="round" style="flex-shrink:0;${style}">` +
      `${ICONS[name]}</svg>`;
  });
  for (const [blob, path] of Object.entries(BLOBS)) html = html.split(blob).join(path);
  const left = html.match(/<x-[a-z-]+|\/_blob\/\w+/);
  if (left) throw new Error(`slide ${id}: "${left[0]}" has no web version — add it to this script`);
  return `<div class="frame" aria-label="Slide ${i + 1}">\n${html.trim()}\n</div>`;
});

