// The captain recruitment deck as one web page: /captains-7a25beb7/.
//
//   node scripts/build-deck-page.mjs <deck dir> <output html>
//
// Run by build-site.sh. The deck is edited as slides on claude.ai; its files
// are copied into decks/captains/ (deck.json plus one slides/<id>.html per
// slide), and this turns them into a page, so changing a slide file is all it
// takes to change the page on the next deploy.
//
// The page is unlisted on purpose: nothing links to it, it is not in the
// sitemap or robots.txt (listing it there would reveal it), it is marked
// noindex, and the build adds no Analytics under this folder.
//
// Each slide is a 1920x1080 <section> with inline styles. Three things only
// the deck viewer understands are converted here: speaker notes (<aside>) are
// dropped, <x-icon> becomes an inline SVG, and uploaded images (/_blob/<id>)
// point at the site's own copies. Anything else unknown stops the build, so a
// slide never ships half-rendered.

